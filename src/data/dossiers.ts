export interface Stage {
  /** 인정하면 생기는 정정 진술 ID */
  id: string;
  /** 무엇에 대한 거짓말인지 */
  topic: string;
  /** 인정하기 전까지 하는 말 */
  cover: string;
  /** 이 거짓말을 무너뜨리는 근거 (AI가 판단하는 기준) */
  breaks: string;
  /** 근거가 일부만 맞을 때의 반응 */
  partial: string;
  /** 인정할 때 털어놓는 것 (이번 대사에 담는다) */
  admits: string;
  /** 인정한 뒤의 입장 */
  after: string;
  /** 인정한 뒤 지금 말할 사실 (짧게. 질문 바로 앞에 놓아 처음 이야기의 거짓을 덮는다) */
  now?: string;
  /** 인정을 받아들이기 위한 최소 조건: 형사가 이 자료 중 하나는 가지고 있어야 한다 (터무니없는 자백을 막는 안전장치) */
  needs: string[];
}

export interface Dossier {
  /** 정체·성격·말투·생활 */
  profile: string;
  /** 그날 이 사람이 직접 겪고 아는 일 */
  night: string;
  /** 모르는 것 */
  unknown: string;
  /** 형사가 자료를 보여 줄 때의 반응 지침 */
  reactions: string;
  /** 형사에게 넘겨줄 수 있는 자기 휴대폰 자료. after가 있으면 그 단계를 인정한 뒤에만 넘긴다 */
  gives: { id: string; what: string; when: string; after?: string }[];
  /** 숨기는 거짓말 (용의자 중 범인만) */
  stages: Stage[];
  /** 숨기는 진실 전체 (인물의 일관성을 위한 것. 인정하기 전에는 절대 말하지 않는다) */
  secret?: string;
  /** 모든 거짓말을 인정한 뒤의 태도 */
  finale?: string;
}

