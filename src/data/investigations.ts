export interface InvestigationDef {
  id: string;
  /** 수사팀 대화와 진행 표시에 쓰는 이름 */
  label: string;
  /** AI 해석기에 주는 설명 */
  topic: string;
  /** 플레이어가 쓸 법한 말 (AI 예시이자 AI 없이 고를 때의 낱말) */
  aliases: string[];
  outputs: string[];
  /** 대상(실물·원본)을 먼저 확보해야 하는 조사. 함께 맡긴다 */
  dependencies?: string[];
  /** 조사의 소요 시간 (밀리초) */
  delayMs: number;
  /** 요청을 받았을 때 수사팀이 하는 말 (무엇을 하겠다) */
  ack: string;
  /** 수사팀이 맡지 않고 다른 길을 알려 주는 요청 */
  redirect?: string;
  /** 다른 길로 받는 자료 (이미 가졌으면 안내 대신 그 자료를 보여 준다) */
  redirectDoc?: string;
  /** 사건 해결에 꼭 필요하지 않은 참고 자료 */
  extra?: boolean;
  /** 조사하다 함께 나온 자료 (결과와 함께 "이것도 확인됐다"며 넘긴다) */
  bonus?: string[];
  /** 이 조사를 맡을 때 수사팀이 "이것도 볼까요?" 하고 권할 만한 조사 */
  related?: string[];
}

